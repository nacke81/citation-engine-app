"""One-time reason_code backfill (t_93ae9b6b). Source: the hand-checked 61-row audit (reason-labels-audit-2026-11.md), with Nate's rulings.

  python db/gen_reason_backfill.py --from-audit <audit.md>   rewrite db/reason_backfill.json from the audit table (rarely needed)
  python db/gen_reason_backfill.py                           write db/011_reason_code_backfill.sql from db/reason_backfill.json

The SQL only sets reason_code, only where it is still null, one row per (biz, directory). It is NOT applied by anything in this repo.
Rows whose label already comes from a stored field the job writes (blocked-cause unknown, no usable result, unsearchable) get no code on purpose:
the next weekly run records the cause in ce_checks.note and the page reads it from there.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
JSON_PATH = os.path.join(HERE, "reason_backfill.json")
SQL_PATH = os.path.join(HERE, "011_reason_code_backfill.sql")

CODES = {
    "Bad Catalog row": "bad_catalog", "No search on site": "no_search", "Paid listing": "paid", "Declined by Mike": "declined",
    "ID check (client)": "id_check", "Login wall": "login_wall", "Contact name required": "contact_name", "Mike's account only": "mike_account",
    "Waiting on directory": "waiting_directory", "Phone verification (client)": "phone_verify", "Site down": "site_down",
    "Blocked: CAPTCHA": "captcha", "Signup form fails": "signup_form", "Blocked: bot wall": "bot_wall", "Form can't take our NAP": "nap",
}
FROM_STORED = {"Search blocked (cause not recorded)", "No usable result", "Unsearchable"}   # left null: derived from ce_checks at read time
# Nate's rulings (11/04), hand-checked against each row's gate text. Negated mentions ("Cloudflare absent", "No CAPTCHA solve spent") do not count.
OVERRIDES = {
    ("SCC", "cylex.us"): "signup_form",           # "Cloudflare absent"; vault fill fails: field not rendered
    ("SCC", "usaypage.com"): "nap",               # "No CAPTCHA solve spent"; the city list cannot hold the canonical city. NAP rule runs ahead of CAPTCHA
    ("SCC", "enrollbusiness.com"): "cloudflare",  # 403 Cf-Mitigated: challenge
    ("SCC", "trustpilot.com"): "bot_wall",        # "Verifying your connection": a wall that is not Cloudflare by name
}


def from_audit(path):
    out = {}
    # The audit names the two businesses in full; this repo holds business keys only (no names), so the first table row seen for each
    # name is mapped by the caller's file: SCC rows come first in the audit table, NM rows second.
    BIZ_NAMES = {}
    for line in open(path, encoding="utf-8"):
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) == 7 and c[1] in ("Needs a person", "Couldn't check") and c[0] not in BIZ_NAMES:
            BIZ_NAMES[c[0]] = ("scc", "nm")[len(BIZ_NAMES)]
    for line in open(path, encoding="utf-8"):
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) != 7 or c[1] not in ("Needs a person", "Couldn't check"): continue
        biz = {"scc": "SCC", "nm": "NM"}[BIZ_NAMES[c[0]]]
        key = (biz, c[2])
        if key in OVERRIDES: code = OVERRIDES[key]
        elif c[5] in FROM_STORED: code = None
        else: code = CODES[c[5]]
        out["%s|%s" % key] = {"section": c[1], "audit_label": c[5], "reason_code": code}
    return out


def sql(rows):
    lines = ["-- One-time reason_code backfill (t_93ae9b6b). Generated by db/gen_reason_backfill.py from db/reason_backfill.json. Run AFTER 011_reason_code.sql.",
             "-- Sets reason_code only, only where it is still null. No insert, no delete, no other column."]
    for k in sorted(rows):
        code = rows[k]["reason_code"]
        if not code: continue
        biz, d = k.split("|")
        lines.append("update public.ce_directory_status set reason_code = '%s' where biz = '%s' and directory = '%s' and reason_code is null;" % (code, biz, d.replace("'", "''")))
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) > 1 and argv[0] == "--from-audit":
        rows = from_audit(argv[1])
        json.dump(rows, open(JSON_PATH, "w", encoding="utf-8"), indent=1, sort_keys=True); print("wrote", JSON_PATH, len(rows)); return 0
    rows = json.load(open(JSON_PATH, encoding="utf-8"))
    open(SQL_PATH, "w", encoding="utf-8", newline="\n").write(sql(rows)); print("wrote", SQL_PATH); return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
